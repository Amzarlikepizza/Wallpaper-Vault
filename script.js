let currentLanguage = 'en';
let currentView = 'pc';

function getText(key) {
  return translations[currentLanguage]?.[key] || translations.en[key] || key;
}

function getWallpaperTitle(wallpaper) {
  return translations[currentLanguage]?.wallpapers?.[wallpaper.titleKey] || translations.en.wallpapers?.[wallpaper.titleKey] || wallpaper.title;
}

function updateResolutionText(resolution, wallpaper, image) {
  const label = getText('resolution');

  if (wallpaper.title === 'Cozy Nigth View') {
    const availableResolutions = wallpaper.variants.map((variant) => variant.label).join(', ');
    if (currentLanguage === 'ar') {
      resolution.innerHTML = `<span class="resolution-label">${label}:</span><span class="resolution-value" dir="ltr">${availableResolutions}</span>`;
    } else {
      resolution.innerHTML = `<span class="resolution-label">${label}:</span> <span class="resolution-value">${availableResolutions}</span>`;
    }
    return;
  }

  const value = `${image.naturalWidth}×${image.naturalHeight}`;
  if (currentLanguage === 'ar') {
    resolution.innerHTML = `<span class="resolution-label">${label}:</span><span class="resolution-value" dir="ltr">${value}</span>`;
  } else {
    resolution.innerHTML = `<span class="resolution-label">${label}:</span> <span class="resolution-value">${value}</span>`;
  }
}

function updateStaticText() {
  const siteTitle = document.querySelector('.site-title');
  const siteSlogan = document.querySelector('.site-slogan');
  const homepageHeading = document.querySelector('.intro h2');
  if (siteTitle) siteTitle.textContent = getText('siteTitle');
  if (siteSlogan) siteSlogan.textContent = getText('slogan');
  if (homepageHeading) homepageHeading.textContent = getText('homepage');
  if (languageToggle) languageToggle.textContent = getText('languageButton');

  document.querySelectorAll('.language-option').forEach((button) => {
    button.setAttribute('aria-label', button.textContent);
  });
}

function downloadWallpaper(path, fileName) {
  const link = document.createElement('a');
  link.href = path;
  link.download = fileName;
  document.body.appendChild(link);
  link.click();
  link.remove();
}

function getVisibleWallpapers() {
  if (currentView === 'phone') {
    const order = ['Green Theme Background', 'Killer Queen Wallpaper'];
    return phoneWallpapers
      .slice()
      .sort((a, b) => {
        const aIndex = order.indexOf(a.title);
        const bIndex = order.indexOf(b.title);
        const aPos = aIndex === -1 ? order.length : aIndex;
        const bPos = bIndex === -1 ? order.length : bIndex;
        return aPos - bPos;
      });
  }

  return wallpapers;
}

function renderWallpapers() {
  if (!wallpaperList) return;

  wallpaperList.innerHTML = '';
  wallpaperList.classList.toggle('phone-view', currentView === 'phone');

  const wallpapersToRender = getVisibleWallpapers();
  wallpapersToRender.forEach((wallpaper) => {
    const card = document.createElement('article');
    card.className = 'wallpaper-card';

    const imageWrap = document.createElement('div');
    imageWrap.className = 'wallpaper-image-wrap';

    const image = document.createElement('img');
    image.className = 'wallpaper-image';
    image.src = wallpaper.path;
    image.alt = `${getWallpaperTitle(wallpaper)} wallpaper`;
    image.loading = 'lazy';

    const details = document.createElement('div');
    details.className = 'wallpaper-details';

    const info = document.createElement('div');
    info.className = 'wallpaper-info';

    const title = document.createElement('h3');
    title.className = 'wallpaper-title';
    title.textContent = getWallpaperTitle(wallpaper);

    const creator = document.createElement('p');
    creator.className = 'wallpaper-creator';
    creator.textContent = `${getText('creator')}: ${getText('creatorName')}`;
    creator.style.display = wallpaper.title === 'Green Theme Background' ? 'block' : 'none';

    const resolution = document.createElement('p');
    resolution.className = 'wallpaper-resolution';
    resolution.textContent = wallpaper.resolution
      ? `${getText('resolution')}: ${wallpaper.resolution}`
      : getText('loadingResolution');

    const actions = document.createElement('div');
    actions.className = 'wallpaper-actions';

    let select = null;

    if (wallpaper.variants.length > 1) {
      select = document.createElement('select');
      select.className = 'resolution-select';
      select.setAttribute('aria-label', `${getText('chooseResolution')} ${wallpaper.title}`);

      wallpaper.variants.forEach((variant, index) => {
        const option = document.createElement('option');
        option.value = index;
        option.textContent = variant.label;
        select.appendChild(option);
      });
    }

    const button = document.createElement('button');
    button.className = 'download-btn';
    button.type = 'button';
    button.textContent = getText('download');

    button.addEventListener('click', () => {
      const selectedVariant = wallpaper.variants[select ? select.value : 0];
      if (selectedVariant) {
        downloadWallpaper(selectedVariant.path, selectedVariant.fileName);
      }
    });

    image.addEventListener('load', () => {
      imageWrap.style.aspectRatio = `${image.naturalWidth}/${image.naturalHeight}`;
      updateResolutionText(resolution, wallpaper, image);
    });

    image.addEventListener('error', () => {
      resolution.textContent = getText('resolutionUnavailable');
    });

    info.append(title);
    if (wallpaper.title === 'Green Theme Background') {
      info.append(creator);
    }
    info.append(resolution);
    if (select) {
      actions.append(select);
    }
    actions.append(button);
    details.append(info, actions);
    imageWrap.appendChild(image);
    card.append(imageWrap, details);
    wallpaperList.appendChild(card);
  });

  document.querySelectorAll('.view-toggle-btn').forEach((button) => {
    const isActive = button.getAttribute('data-view') === currentView;
    button.classList.toggle('is-active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });
}

